#!/usr/bin/env bash
# Builds the v3-only client into both apps, at src/lib/sign-client-v3: one self-contained ESM
# bundle (the Sign v3 WASM embedded, every dependency inlined). The apps then build from source,
# with no npm package for the client.
#
# The client is scripts/sign-client-v3: v2's SignClient API over the Sign v3 engine alone, with
# no v2 fallback. The engine is the WASM in walletconnect-monorepo, packages/sign-client/src/v3/wasm.
# The bundle's types are the .d.ts files already in each app; they change only with the client's API.
#
# MONOREPO_DIR defaults to a walletconnect-monorepo checkout next to web-examples, with its
# dependencies installed.
set -euo pipefail

here=$(cd "$(dirname "$0")/.." && pwd)
mono=$(cd "${MONOREPO_DIR:-$here/../../walletconnect-monorepo}" && pwd)
pkg=$mono/packages/sign-client
wasm=$pkg/src/v3/wasm
[ -f "$wasm/wasm-data.ts" ] || { echo "no $wasm: is this the Sign v3 branch?" >&2; exit 1; }

rev=$(git -C "$mono" rev-parse --short HEAD)
git -C "$mono" diff --quiet HEAD -- packages/sign-client/src/v3/wasm || rev="$rev+local"
engine=$(grep -o 'yttrium [0-9a-f]*[+a-z]*' "$wasm/wasm-data.ts" | head -1)
banner="// The v3-only Sign client (v3/scripts/sign-client-v3), engine $engine from walletconnect-monorepo $rev. Generated by v3/scripts/vendor-sign-client.sh; don't edit."

build=$(mktemp -d)
trap 'rm -rf "$build"' EXIT
cp "$here/scripts/sign-client-v3/"*.ts "$build/"
mkdir "$build/wasm"
cp "$wasm/sign_v3.js" "$wasm/wasm-data.ts" "$build/wasm/"

for app in dapp wallet; do
  out=$here/$app/src/lib/sign-client-v3
  NODE_PATH=$mono/node_modules "$mono/node_modules/.bin/esbuild" "$build/index.ts" --bundle --minify \
    --platform=browser --format=esm --target=es2022 --banner:js="$banner" \
    --outfile="$out/index.js" --log-level=warning
  # The Community License travels with redistributed copies, with this notice.
  cp "$pkg/LICENSE.md" "$out/LICENSE.md"
  printf '%s\n\n%s\n' "Portions © 2025 Reown, Inc. All Rights Reserved" \
    "This folder is a build of the Sign v3 client from @walletconnect/sign-client, licensed under the WalletConnect Community License in LICENSE.md." \
    >"$out/NOTICE.md"
  echo "vendored $out: $(wc -c <"$out/index.js" | tr -d ' ') bytes"
done
echo "monorepo $rev, engine $engine"
